UA = "slax-kitchen sources (+https://github.com/Fullaxx/slax-kitchen)"


def _get(url: str, dest: str) -> None:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=300) as r, open(dest + ".part", "wb") as f:
        shutil.copyfileobj(r, f)
    os.replace(dest + ".part", dest)


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def project_tarball(root: str, state: dict, name: str, dest_dir: str) -> str:
    """`git archive` of the recorded commit, with every recorded submodule inside it, as a
    deterministic .tar.gz. GitHub's automatic source archives omit submodules."""
    commit = state["commit"]
    out = os.path.join(dest_dir, f"{name}-{commit[:12]}-source.tar.gz")
    with tempfile.TemporaryDirectory() as tmp:
        main = os.path.join(tmp, "main.tar")
        subprocess.run(["git", "-C", root, "archive", "--format=tar", f"--prefix={name}/",
                        "-o", main, commit], check=True)
        with tarfile.open(main, "a") as tar:
            for path, sha in sorted((state.get("submodules") or {}).items()):
                part = os.path.join(tmp, "sub.tar")
                subprocess.run(["git", "-C", os.path.join(root, path), "archive", "--format=tar",
                                f"--prefix={name}/{path}/", "-o", part, sha], check=True)
                with tarfile.open(part) as sub:
                    for m in sub.getmembers():
                        tar.addfile(m, sub.extractfile(m) if m.isfile() else None)
            info = tarfile.TarInfo(f"{name}/SUBMODULES.txt")
            body = "".join(f"{sha} {path}\n" for path, sha in
                           sorted((state.get("submodules") or {}).items())).encode()
            info.size, info.mtime = len(body), 0
            import io
            tar.addfile(info, io.BytesIO(body))
        with open(main, "rb") as src, open(out, "wb") as raw:
            with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as gz:
                shutil.copyfileobj(src, gz)
    return out


def fetch_debian_style_source(source: str, version: str, builder: dict, dest: str) -> list[str]:
    """A source package at an exact version: apt-get source when the host has deb-src,
    else Launchpad (Ubuntu builder) or snapshot.debian.org (Debian builder), every file
    verified against the .dsc's Checksums-Sha256."""
    os.makedirs(dest, exist_ok=True)
    before = set(os.listdir(dest))
    if shutil.which("apt-get"):
        r = subprocess.run(["apt-get", "source", "--download-only", f"{source}={version}"],
                           cwd=dest, capture_output=True, text=True)
        new = sorted(set(os.listdir(dest)) - before)
        if r.returncode == 0 and any(n.endswith(".dsc") for n in new):
            return new
    noepoch = version.split(":", 1)[-1]
    dsc_name = f"{source}_{noepoch}.dsc"
    if builder.get("id") == "ubuntu":
        base = (f"https://launchpad.net/ubuntu/+archive/primary/+sourcefiles/"
                f"{source}/{urllib.parse.quote(version, safe='')}/")
        urls = {dsc_name: base + dsc_name}
        _get(urls[dsc_name], os.path.join(dest, dsc_name))
        text = open(os.path.join(dest, dsc_name), errors="replace").read()
        m = re.search(r"^Checksums-Sha256:\n((?:[ \t].+\n?)+)", text, re.M)
        if not m:
            raise RuntimeError(f"{dsc_name}: no Checksums-Sha256")
        got = [dsc_name]
        for ln in m.group(1).strip().splitlines():
            sha, _size, name = ln.split()
            path = os.path.join(dest, name)
            _get(base + name, path)
            if _sha256(path) != sha:
                raise RuntimeError(f"{name}: sha256 does not match {dsc_name}")
            got.append(name)
        return got
    info = json.load(urllib.request.urlopen(urllib.request.Request(
        f"https://snapshot.debian.org/mr/package/{source}/{urllib.parse.quote(version, safe='')}"
        "/srcfiles?fileinfo=1", headers={"User-Agent": UA}), timeout=120))
    got = []
    for h, entries in (info.get("fileinfo") or {}).items():
        name = entries[0]["name"]
        path = os.path.join(dest, name)
        _get(f"https://snapshot.debian.org/file/{h}", path)
        if hashlib.sha1(open(path, "rb").read()).hexdigest() != h:
            raise RuntimeError(f"{name}: sha1 does not match snapshot's hash")
        got.append(name)
    return got


def fetch_built(doc: dict, prov: dict, dest: str) -> list[dict]:
    """Gather the source of everything classed `built`, and the project tree(s)."""
    os.makedirs(dest, exist_ok=True)
    assets = []
    kitchen = prov.get("kitchen") or {}
    if kitchen.get("commit"):
        out = project_tarball(REPO, kitchen, "slax-kitchen", dest)
        assets.append({"what": "slax-kitchen at the recorded commit, with submodules",
                       "for": "(kitchen)", "file": os.path.basename(out), "sha256": _sha256(out)})
    project = prov.get("project")
    root = provenance.project_root()
    if project and project.get("commit") and root:
        out = project_tarball(root, project, os.path.basename(os.path.abspath(root)), dest)
        assets.append({"what": "the project at the recorded commit, with submodules",
                       "for": "(project)", "file": os.path.basename(out), "sha256": _sha256(out)})
    builder = doc.get("builder") or {}
    for comp in doc["components"]:
        if comp["class"] == "built" and comp.get("source_package"):
            sp = comp["source_package"]
            sub = os.path.join(dest, f"{sp['source']}_{sp['version'].split(':', 1)[-1]}")
            for name in fetch_debian_style_source(sp["source"], sp["version"], builder, sub):
                p = os.path.join(sub, name)
                assets.append({"what": f"source of {comp['what']}", "for": comp["path"],
                               "file": os.path.relpath(p, dest), "sha256": _sha256(p)})
        for part in comp.get("parts") or []:
            if part.get("class") != "built":
                continue
            for src in part.get("sources") or []:
                name = os.path.basename(urllib.parse.urlsplit(src["url"]).path)
                p = os.path.join(dest, name)
                _get(src["url"], p)
                if _sha256(p) != src["sha256"]:
                    raise RuntimeError(f"{name}: sha256 does not match the build claim")
                assets.append({"what": f"source of {part['member']}", "file": name,
                               "for": f"{comp['path']}:{part['member']}", "sha256": src["sha256"]})
            cfg = part.get("config") or {}
            if cfg.get("file"):
                # Beside the binary the build used, found from its recorded location; the
                # kitchen's build/ is where tools/build-busybox.sh writes by default.
                roots = {"kitchen": REPO, "project": provenance.project_root()}
                loc = part.get("location") or {}
                candidates = [os.path.join(REPO, "build", cfg["file"])]
                if roots.get(loc.get("root")):
                    candidates.insert(0, os.path.join(roots[loc["root"]],
                                                      os.path.dirname(loc["path"]), cfg["file"]))
                local = next((c for c in candidates
                              if os.path.isfile(c) and _sha256(c) == cfg.get("sha256")), None)
                if not local:
                    raise RuntimeError(f"{cfg['file']}: not found beside the build, or it is "
                                       "not the config the build claim names")
                shutil.copy2(local, os.path.join(dest, cfg["file"]))
                assets.append({"what": f"build configuration of {part['member']}",
                               "for": f"{comp['path']}:{part['member']}",
                               "file": cfg["file"], "sha256": cfg["sha256"]})
    return assets


