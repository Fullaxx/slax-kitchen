def check_local_inputs(prov: dict) -> None:
    """Mark every recorded local input `in_archive`: does the recorded commit of the
    checkout it sat in hold exactly this content? Git answers without a checkout of that
    commit, so this works from any clone that has it."""
    roots = {"kitchen": REPO, "project": provenance.project_root()}
    commits = {"kitchen": (prov.get("kitchen") or {}).get("commit"),
               "project": (prov.get("project") or {}).get("commit")}
    for r in prov.get("recipes") or []:
        inputs = [r["recipe_file"]] if r.get("recipe_file") else []
        inputs += [li for st in r.get("steps") or [] for li in st.get("local_inputs") or []]
        for li in inputs:
            if li.get("outside"):
                continue
            root, commit = roots.get(li.get("root")), commits.get(li.get("root"))
            if not root or not commit:
                li["in_archive"] = False
                li["why"] = ("set PROJECT_ROOT to the project checkout" if li.get("root") == "project"
                             else "no commit recorded")
                continue
            li["in_archive"] = provenance.git_digest(root, commit, li["path"], li["kind"]) == li["digest"]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="kitchen sources", description=__doc__.split("\n\n")[0])
    ap.add_argument("iso")
    ap.add_argument("--provenance", help="default: <iso>.provenance.json")
    ap.add_argument("--json", help="write the machine-readable manifest here")
    ap.add_argument("--markdown", help="write the human-readable manifest here")
    ap.add_argument("--fetch", metavar="DIR", help="gather the source of what was built here")
    ap.add_argument("--allow-dirty", action="store_true",
                    help="accept uncommitted work: an image built from a kitchen tree with "
                         "uncommitted changes, and recipe files and copied-in inputs the "
                         "recorded commit does not hold (untracked or gitignored ones "
                         "too), which are then classed as if it did")
    ap.add_argument("--strict", action="store_true",
                    help="a download with no upstream_source, or none pinned by sha256, "
                         "is unresolved rather than a warning")
    a = ap.parse_args(argv[1:])
    # xorriso lists the image. git on every run, not only --fetch: every local input is
    # looked up at its recorded commit (provenance.git_digest), which the first version of
    # this check missed -- --fetch was where git was visible, not where it was first used.
    need.require(["xorriso", "git"], "kitchen sources")

    prov_path = a.provenance or a.iso + ".provenance.json"
    if not os.path.isfile(prov_path):
        print(f"kitchen sources: no provenance at {prov_path}\n"
              f"  `kitchen pack` writes it beside the ISO; rebuild with this kitchen.",
              file=sys.stderr)
        return 2
    prov = json.load(open(prov_path))
    import yaml
    sources_yaml = yaml.safe_load(open(os.path.join(REPO, "compat", "sources.yaml"))) or {}
    target, info = base_target(prov, sources_yaml)
    stock = stock_index(target, os.path.join(REPO, "docs", "30-inventory", "manifests"))
    # A LISTING THAT FAILED IS NOT AN IMAGE WITH NOTHING IN IT. classify() accounts for the
    # files it is given, so an empty listing -- xorriso 1.5.6 exits 0 on a file it cannot
    # read as an ISO -- used to come out "unresolved 0" and pass, --strict included: a
    # pass for an image nobody had examined. diff._entries() now refuses such a listing.
    import diff
    try:
        files = iso_files(a.iso)
        check_local_inputs(prov)
        # Unpack the initramfs only when there is something to learn: it is not the stock
        # one (an untouched initrfs.img is answered by its own sha256) and this target has a
        # manifest to compare it against. Otherwise the xz is work whose result is unusable.
        irfs = files.get("slax/boot/initrfs.img")
        members = (initramfs_members(a.iso)
                   if irfs and stock["initramfs"]
                   and stock["files"].get("slax/boot/initrfs.img") != irfs else None)
    except diff.ListingError as e:
        print(f"kitchen sources: {e} -- so nothing in it can be accounted for", file=sys.stderr)
        return 2
    doc = classify(files, stock, prov, target, info, a.allow_dirty, a.strict,
                   initramfs=members)
    if ((prov.get("pack") or {}).get("iso") or {}).get("sha256") not in (None, _sha256(a.iso)):
        doc["unresolved"].append({"path": "(image)", "reason": "the ISO's sha256 is not the one "
                                  "its provenance records -- it changed after pack"})
        doc["summary"]["unresolved"] = len(doc["unresolved"])

    rc = 1 if doc["unresolved"] else 0
    if a.fetch and not doc["unresolved"]:
        try:
            doc["assets"] = fetch_built(doc, prov, a.fetch)
        except (OSError, RuntimeError, subprocess.CalledProcessError, ValueError) as e:
            doc["unresolved"].append({"path": "(fetch)", "reason": str(e)})
            doc["summary"]["unresolved"] = len(doc["unresolved"])
            rc = 1
    if a.json:
        with open(a.json, "w") as f:
            json.dump(doc, f, indent=1, sort_keys=True)
            f.write("\n")
    if a.markdown:
        open(a.markdown, "w").write(markdown(doc))

    s = doc["summary"]
    print(f"sources  {doc['image'].get('name')}  (base {target or 'unknown'})")
    print("  " + "  ".join(f"{c} {s[c]}" for c in CLASSES))
    for w in doc["warnings"]:
        print(f"  warning: {w}")
    for n in doc["not_redistributable"]:
        print(f"  not redistributable: {n['recipe']} -- {n['why']}")
    for u in doc["unresolved"]:
        print(f"  UNRESOLVED {u['path']}: {u['reason']}")
    for asset in doc.get("assets") or []:
        print(f"  fetched  {asset['file']}")
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv))
