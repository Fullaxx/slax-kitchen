#!/usr/bin/env python3
"""kitchen sources -- what is in a built ISO, and where the source of each part lives.

    kitchen sources <iso> [--provenance FILE] [--json FILE] [--markdown FILE]
                          [--fetch DIR] [--allow-dirty] [--strict]

A published image carries the source of what its build compiled, built or modified, and
says where each upstream publishes the source of everything included unmodified. This
command works out which is which, for every file in the ISO, from evidence rather than
from a list someone keeps:

  slax       sha256 equals the committed stock manifest for the base image
             (docs/30-inventory/manifests/{bootfiles,isofiles,initramfs}-<target>.sha256)
  debian     a bundle a recorded bundle.packages step produced, byte for byte: its packages
  slackware  the same, for Slackware packages
  prebuilt   a recorded download, installed unmodified -- a tarball or a payload -- or
             bytes pack copied from the build host (the MBR)
  built      compiled or assembled here: GRUB's EFI image, a busybox with a verified build
             claim, a binary a bundle.script declares
  ours       written or generated by a recipe or by kitchen itself; a script's bundle
             lists beside it each file the script says it fetched (KITCHEN-FETCHED)
  unresolved anything else, and the command exits 1

The evidence is the image's provenance sidecar (<iso>.provenance.json, written by `kitchen
pack`). A file matches a recorded step only if its sha256 is the one recorded, so a bundle
altered after the build is unresolved rather than silently attributed. A repacked
initramfs is opened and its members compared with the stock manifest one by one, because
"the parts that match Slax are Slax" is a claim, and a claim has to be counted.

WHAT WEAKENS A POINTER IS SAID. A download with no upstream_source, and a download the
recipe pinned no sha256 for (what it fetched is what that server served that day), are
warnings here and unresolved under --strict.

OFFLINE unless --fetch. With --fetch DIR it gathers the source of everything classed
`built`, plus the project tree at the recorded commit WITH its submodules (GitHub's
automatic source archives leave submodules out). Unmodified upstream parts are pointed
at, not fetched.
"""
